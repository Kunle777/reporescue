from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

APP_DIR = Path(__file__).resolve().parent
FIXTURE_DIR = APP_DIR.parent / "fixtures" / "checkout_service"

app = FastAPI(
    title="RepoRescue API",
    description="Local-first, test-backed patch verification demo.",
    version="0.1.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173", "http://127.0.0.1:5173"],
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)


class InvestigationRequest(BaseModel):
    scenario: str = "negative-discount"


def run_tests(workspace: Path) -> dict[str, Any]:
    started = time.perf_counter()
    try:
        result = subprocess.run(
            [sys.executable, "-m", "pytest", "-q", "tests"],
            cwd=workspace,
            capture_output=True,
            text=True,
            timeout=20,
            check=False,
        )
        output = (result.stdout + "\n" + result.stderr).strip()
        return {
            "passed": result.returncode == 0,
            "exit_code": result.returncode,
            "output": output[-6000:],
            "duration_ms": round((time.perf_counter() - started) * 1000),
        }
    except subprocess.TimeoutExpired as exc:
        output = ((exc.stdout or "") + "\n" + (exc.stderr or "")).strip()
        return {
            "passed": False,
            "exit_code": None,
            "output": f"Test run timed out.\n{output}"[-6000:],
            "duration_ms": round((time.perf_counter() - started) * 1000),
        }


@app.get("/api/health")
def health() -> dict[str, str]:
    return {"status": "ok", "service": "RepoRescue API", "mode": "local-demo-no-model-calls"}


@app.post("/api/demo/investigate")
def investigate(request: InvestigationRequest) -> dict[str, Any]:
    if request.scenario != "negative-discount":
        return {"status": "error", "message": "Unknown demo scenario."}
    if not FIXTURE_DIR.is_dir():
        return {"status": "error", "message": "Bundled demo repository is missing."}

    with tempfile.TemporaryDirectory(prefix="reporescue-") as temp_dir:
        workspace = Path(temp_dir) / "checkout_service"
        shutil.copytree(FIXTURE_DIR, workspace)

        baseline = run_tests(workspace)

        # The patch is deliberately deterministic for this first vertical slice.
        # Later, the model will propose a diff; the trusted verifier stays separate.
        pricing_file = workspace / "src" / "pricing.py"
        source = pricing_file.read_text(encoding="utf-8")
        old_line = "    return price - discount"
        new_line = "    return max(0, price - discount)"
        if old_line not in source:
            return {
                "status": "error",
                "message": "Expected vulnerable line was not found; refusing to patch an unexpected fixture.",
                "baseline": baseline,
            }
        pricing_file.write_text(source.replace(old_line, new_line, 1), encoding="utf-8")

        after = run_tests(workspace)
        patch = {
            "file": "src/pricing.py",
            "before": "    return price - discount",
            "after": "    return max(0, price - discount)",
            "reason": "Clamp the final price at zero so discounts cannot produce a negative charge.",
        }

        verified = baseline["passed"] is False and after["passed"] is True
        return {
            "status": "complete",
            "scenario": "Negative discount result",
            "repository": "checkout-service-demo",
            "mode": "deterministic-local-demo",
            "summary": (
                "The baseline reproduced a failure, and the demo patch passed the bundled tests."
                if verified
                else "The expected baseline-to-passing-test sequence did not occur. Inspect the test output."
            ),
            "verdict": "TESTS_PASSED" if verified else "INCONCLUSIVE",
            "baseline": baseline,
            "verification": after,
            "patch": patch,
            "limitations": [
                "The patch is a deterministic demo patch, not generated by an AI model.",
                "Only the bundled fixture is executed; arbitrary repositories are not accepted.",
                "Passing this test suite is evidence, not a proof of universal correctness.",
            ],
        }
